/**
 * Сигнал сенсора: факты о текущей сессии, которые видит только
 * session-слот. Оверлей не получает ctx и пропсы слота — только этот
 * снапшот (паттерн «сенсор + оверлей», так же устроены
 * dsh-chibi-pet и c-ling/dsh-plugin-pet).
 */
import type { PetState } from './states'
import { deriveState, type MoodFacts } from './mood'

/**
 * Снапшот сигнала: факты сессии плюс служебные поля сенсора.
 *
 * `MoodFacts` — то, что нужно для выбора состояния; здесь оно расширено
 * тем, что интересно только UI. Разделение важно: `runForMs` и `idleForMs`
 * в снапшоте намеренно ОТСУТСТВУЮТ (см. `runStartedAt`/`runEndedAt`),
 * иначе тип позволял бы положить туда протухающее число.
 *
 * Отсюда же требование к сенсору: он кладёт в сигнал РОВНО эти поля.
 * Лишнее поле прошло бы мимо типов, но `signal.set` сравнивает снапшоты
 * поверхностно и на каждом рендере публиковал бы «изменение», а оверлей
 * перерисовывался бы вхолостую.
 */
export interface SessionSignal extends Omit<MoodFacts, 'runForMs' | 'idleForMs'> {
  /** Есть ли привязанная сессия (сенсор смонтирован в её слоте). */
  focused: boolean
  sessionId: string | null
  /** Агент в данный момент выполняет ход. */
  running: boolean
  /** Идут tool-вызовы (иначе модель просто генерирует текст). */
  working: boolean
  /** Ключ ожидающего взаимодействия (approval/permission) либо null. */
  pendingKey: string | null
  /** Последняя ошибка агента, если ещё не сброшена. */
  error: string | null
  /**
   * Есть ли текст в поле ввода — человек начал печатать.
   *
   * Отдельной «метки последнего нажатия» здесь нет намеренно: пустой
   * черновик и есть «ничего не происходит», отсчитывать от него нечего.
   */
  typing: boolean
  /**
   * Момент начала текущего хода (Date.now()), 0 если ход не идёт.
   *
   * Храним метку, а не «сколько прошло»: снапшот обновляется только при
   * смене фактов, поэтому готовое число протухало бы между рендерами —
   * кошка не легла бы, пока ход не завершится. Сколько прошло, считает
   * тот, кто принимает решение, в момент решения.
   */
  runStartedAt: number
  /**
   * Момент завершения последнего хода (Date.now()), 0 если ход ещё ни
   * разу не завершался.
   *
   * От этой метки отсчитывается сон при бездействии. Именно от КОНЦА
   * хода, а не от последнего нажатия клавиши: иначе кошка засыпала бы,
   * пока человек вдумчиво читает длинный ответ, ничего не нажимая.
   */
  runEndedAt: number
}

export const INITIAL_SIGNAL: SessionSignal = {
  focused: false,
  sessionId: null,
  running: false,
  working: false,
  pendingKey: null,
  error: null,
  typing: false,
  runStartedAt: 0,
  runEndedAt: 0,
}

/**
 * Сброс, когда сенсор размонтирован (сессия закрыта/переключена).
 * Отдельного объекта нет намеренно: сравнение в сигнале поверхностное,
 * поэтому `replace({ ...INITIAL_SIGNAL })` в сенсоре очищает снапшот.
 */
export const CLEARED_SIGNAL: SessionSignal = INITIAL_SIGNAL

/**
 * Снапшот сигнала → состояние котика. Чистая функция, покрыта тестами.
 *
 * Здесь считается только ЦЕЛЕВОЕ состояние по фактам сессии. Доигрывание
 * одноразовых переходов `lie`/`wake` и последующий уход в `sleep`/`sit` —
 * забота advanceMood: он вызывается при отрисовке, где уже известен
 * `current`. Смешивать это в одну функцию не стоит, иначе теряется
 * разница между «куда идём» и «что показываем сейчас».
 *
 * `now` передаётся аргументом, а не берётся из Date.now() внутри: иначе
 * функция перестала бы быть чистой и её нельзя было бы проверить тестом
 * на пороге «ход идёт уже 10 секунд».
 */
export function signalToState(signal: SessionSignal, now: number = Date.now()): PetState {
  const facts: MoodFacts = {
    running: signal.running,
    working: signal.working,
    pendingKey: signal.pendingKey,
    error: signal.error,
    typing: signal.typing,
    runForMs: runSince(signal.runStartedAt, now),
    // Пока ход идёт, «сколько мы бездельничаем» смысла не имеет: idle не
    // может быть больше нуля, иначе два таймера спорили бы друг с другом.
    idleForMs: signal.running ? 0 : runSince(signal.runEndedAt, now),
  }

  return deriveState(facts)
}

/**
 * Сколько прошло с метки времени.
 *
 * Метка 0 — события ещё не было (ход не идёт / ни один ход не завершался
 * или сенсор ещё не отчитывался). Возвращаем 0, а не отрицательную
 * величину: ноль означает «рано», и это безопасный дефолт — кошка просто
 * сидит. Метка из будущего (часы поехали) тоже даёт 0, а не минус.
 */
export function runSince(at: number, now: number): number {
  if (at === 0) return 0
  return Math.max(0, now - at)
}
