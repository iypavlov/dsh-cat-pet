/**
 * Факты сессии → состояние кошки.
 *
 * Логика привязана к тому, что ВИДНО на экране. Кошка спит в двух случаях:
 *
 *  1. Агент думает долго — человек всё равно смотрит и ждёт, и спящий
 *     рядом кот уместен: он «ждёт вместе с тобой».
 *  2. После хода прошло много времени — экран перед глазами, но в нём
 *     давно ничего не происходит. Сидящая без дела кошка выглядит
 *     выключенной игрушкой, а спящая — живой.
 *
 *   агент думает долго       → lie → sleep  (ждёт вместе с тобой)
 *   агент закончил, ход твой → wake → sit   (бодрая, ждёт тебя)
 *   долго ничего не было     → lie → sleep  (уснула от скуки)
 *   человек начал печатать   → wake → sit   (проснулась)
 *   агент ждёт решения       → sit          (нужно твоё внимание)
 *   ошибка агента            → sit          (не спим, когда всё сломалось)
 *
 * Почему НЕ «спать, когда вкладка скрыта»: свёрнутая вкладка или
 * неактивное окно означают, что кошку всё равно никто не видит. Реакция
 * имеет смысл только на то, что происходит на глазах.
 *
 * Переходы lie/wake проигрываются один раз и замирают на последнем кадре,
 * поэтому после `lie` кошка должна «доехать» до `sleep`, а после `wake` —
 * вернуться в `sit`. Этим занимается advanceMood.
 */

/** Состояния кошки: набор «бытовой», а не статус агента напрямую. */
export const PET_STATES = ['sit', 'lie', 'sleep', 'wake'] as const

export type PetState = (typeof PET_STATES)[number]

/** Состояние по умолчанию и при любой нераспознанной ситуации. */
export const FALLBACK_STATE: PetState = 'sit'

/** Состояния-переходы: играются один раз и замирают на последнем кадре. */
const ONE_SHOT_STATES: readonly PetState[] = ['lie', 'wake']

export function isOneShot(state: PetState): boolean {
  return ONE_SHOT_STATES.includes(state)
}

export interface MoodFacts {
  /** Агент в данный момент выполняет ход. */
  running: boolean
  /** Идут tool-вызовы. */
  working: boolean
  /** Ключ ожидающего взаимодействия: агент ждёт решения пользователя. */
  pendingKey: string | null
  /** Последняя ошибка агента. */
  error: string | null
  /** Сколько миллисекунд идёт текущий ход (0, если ход не идёт). */
  runForMs: number
  /** Сколько миллисекунд прошло с конца последнего хода (0, если ход идёт). */
  idleForMs: number
  /** Есть ли текст в поле ввода — человек начал печатать. */
  typing: boolean
}

/**
 * Минимальная длительность хода, при которой кошка ложится.
 *
 * Короткий ход — это 3-5 секунд, а полный цикл «лечь → поспать → встать»
 * занимает около 8,5 с. Без порога кошка дёргалась бы: не успела лечь,
 * как уже надо вставать. Порог выбран так, чтобы успевало отыграть
 * хотя бы начало сна.
 */
export const LIE_AFTER_RUN_MS = 10_000

/**
 * Сколько тишины после хода достаточно, чтобы кошка легла.
 *
 * Мера намеренно грубая: считаем НЕ «время с последнего нажатия клавиши»,
 * а время с конца хода. Иначе кошка засыпала бы, пока человек вдумчиво
 * читает длинный ответ, ничего не нажимая, — это выглядит как «уснула,
 * пока я на неё смотрю».
 *
 * Одна минута — компромисс: не мешает читать ответ, но оживляет экран,
 * если человек отошёл. Брать здесь 10 с (как у хода) нельзя: тогда кошка
 * ложилась бы, пока ответ ещё читают.
 */
export const SLEEP_AFTER_IDLE_MS = 60_000

/**
 * Идёт ли ход прямо сейчас.
 *
 * Ожидание решения пользователя сюда НЕ входит: в этот момент агент
 * остановлен и ждёт человека, поэтому кошка должна проснуться. Раньше
 * ожидание считалось занятостью — это было ошибкой, кошка продолжала
 * спать именно тогда, когда от пользователя ждали действия.
 */
export function isAgentBusy(facts: MoodFacts): boolean {
  return facts.running
}

/**
 * Нужно ли кошке проснуться ради человека.
 *
 * Это не «занятость», а наоборот — сигнал, что ход перешёл к пользователю:
 * агент ждёт подтверждения или упал с ошибкой. В обоих случаях кошка
 * должна быть на виду.
 */
export function needsAttention(facts: MoodFacts): boolean {
  return (facts.pendingKey !== null && facts.pendingKey !== '') || (facts.error !== null && facts.error !== '')
}

/**
 * Долго ли идёт текущий ход — то есть стоит ли ложиться.
 *
 * Если ход короткий, кошка просто сидит: мельтешение «легли-встали» за
 * пять секунд выглядит как сбой, а не как поведение.
 */
export function isLongRun(facts: MoodFacts): boolean {
  return facts.running && facts.runForMs >= LIE_AFTER_RUN_MS
}

/**
 * Давно ли в сессии ничего не происходило.
 *
 * Считается только когда ход НЕ идёт: во время хода «тишина» смысла не
 * имеет, там работает isLongRun со своим порогом.
 */
export function isIdleTooLong(facts: MoodFacts): boolean {
  return !facts.running && facts.idleForMs >= SLEEP_AFTER_IDLE_MS
}

/**
 * Целевое состояние по фактам сессии.
 *
 * Одноразовые переходы здесь НЕ выбираются: `lie` и `wake` — это реакция
 * на смену обстановки, а не устойчивое состояние. Ими управляют
 * transitionState/advanceMood, у которых есть память о том, что
 * показывается сейчас.
 */
export function deriveState(facts: MoodFacts): PetState {
  // Ожидание решения и ошибка будят кошку: спать, когда тебя ждут или
  // когда всё сломалось, — странно.
  if (needsAttention(facts)) return FALLBACK_STATE

  // Человек начал печатать — кошка просыпается, даже если ход ещё не
  // стартовал.
  if (facts.typing) return FALLBACK_STATE

  // Ход идёт долго — можно ложиться и спать.
  if (isLongRun(facts)) return 'sleep'

  // Ход давно кончился и ничего не происходит — тоже сон.
  if (isIdleTooLong(facts)) return 'sleep'

  // Всё остальное время кошка бодра: агент закончил и ход твой, или ход
  // настолько короткий, что ложиться бессмысленно.
  return FALLBACK_STATE
}

/**
 * Довести состояние с учётом незавершённых одноразовых переходов.
 *
 * Правила:
 *   - пока проигрывается `lie`/`wake`, состояние не меняется, пока
 *     переход не доиграет (иначе кадры дёргались бы на полпути);
 *   - после `lie` кошка уходит в `sleep` — цель перехода;
 *   - после `wake` кошка возвращается в `sit`;
 *   - засыпание и пробуждение запускаются сменой обстановки, а не
 *     каждым рендером, поэтому решение принимается по `target`/`was`.
 *
 * @param current состояние, которое показывается сейчас
 * @param finished доиграл ли текущий одноразовый переход до конца
 * @param target состояние, к которому стремимся по фактам сессии
 */
export function advanceMood(current: PetState, finished: boolean, target: PetState): PetState {
  if (current === 'lie') return finished ? 'sleep' : 'lie'
  if (current === 'wake') return finished ? FALLBACK_STATE : 'wake'
  return target
}

/**
 * Какое состояние показать, зная предыдущее и целевое.
 *
 * Отдельная функция для моментов смены: именно здесь появляются
 * одноразовые переходы `lie` и `wake`, которых нет в deriveState.
 *
 *   sit  → sleep  : кошка ложится, потом уснёт (advanceMood доиграет)
 *   sleep → sit   : кошка встаёт, потом сядет
 *   всё остальное : просто целевое состояние
 */
export function transitionState(previous: PetState, target: PetState): PetState {
  if (previous === 'sit' && target === 'sleep') return 'lie'
  if (previous === 'sleep' && target === 'sit') return 'wake'
  return target
}
